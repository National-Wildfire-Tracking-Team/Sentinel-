/**
 * fire-danger-stack.mjs
 * Sentinel Fire Danger & Fuels: the cloud/fire-danger builder (Python) on
 * Lambda in us-east-1, its outputs served through the existing
 * SentinelDataServices CloudFront distribution at /fire-danger/*.
 *
 *   EventBridge (rate 3 h) ─▶ builder ─▶ s3://sentinel-fire-danger-<account>/fire-danger/v1/…
 *          ▲ HTTPS, ~42 requests per run, no key
 *   USDA Forest Service FEMS (NFDRS station values)
 *   browser ─▶ CloudFront /fire-danger/* ─OAC─▶ that bucket (read-only)
 *
 * Browsers never call FEMS: they read the published station file, one
 * station's history on demand, and the manifest. The builder's role can
 * write its own logs and the fire-danger/ prefix, nothing else.
 *
 * Schedule: FEMS adds one observed day per day and its forecast changes
 * during the day; every 3 hours picks both up within hours without loading
 * FEMS. A run whose data is unchanged writes only the manifest.
 */

import { CfnOutput, Duration, RemovalPolicy, Stack, Tags } from 'aws-cdk-lib';
import * as lambda from 'aws-cdk-lib/aws-lambda';
import * as logs from 'aws-cdk-lib/aws-logs';
import * as iam from 'aws-cdk-lib/aws-iam';
import * as cloudwatch from 'aws-cdk-lib/aws-cloudwatch';
import * as cwActions from 'aws-cdk-lib/aws-cloudwatch-actions';
import * as sns from 'aws-cdk-lib/aws-sns';
import * as subs from 'aws-cdk-lib/aws-sns-subscriptions';
import * as s3 from 'aws-cdk-lib/aws-s3';
import * as events from 'aws-cdk-lib/aws-events';
import * as targets from 'aws-cdk-lib/aws-events-targets';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const SERVICE_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../../cloud/fire-danger');

export const FIRE_DANGER = {
  dir: 'fire-danger',
  pathPrefix: '/fire-danger', // S3 keys start with fire-danger/ so CloudFront passes paths through unchanged
  keyPrefix: 'fire-danger/',
  frontendEnvVar: 'VITE_FIRE_DANGER_URL',
  region: 'us-east-1',
  metricsNamespace: 'Sentinel/FireDanger',
  retentionDays: 3, // runs are immutable; 3 days covers CDN-cached manifests, a failed day and debugging
  builderMemoryMb: 512, // stdlib only; a national run holds ~50k rows
  builderTimeoutSeconds: 300, // measured ~60 s for 42 batches; leaves room for retries
  builderScheduleHours: 3,
};

/** Deterministic, so the distribution's stack can name it without a cross-stack reference. */
export function fireDangerBucketName(account) {
  return `sentinel-fire-danger-${account}`;
}

export class FireDangerStack extends Stack {
  /**
   * @param {import('constructs').Construct} scope
   * @param {string} id
   * @param {import('aws-cdk-lib').StackProps & { alarmEmail?: string, distributionId?: string }} props
   */
  constructor(scope, id, props) {
    super(scope, id, props);
    const { alarmEmail, distributionId } = props;
    const cfg = FIRE_DANGER;

    Tags.of(this).add('project', 'sentinel');
    Tags.of(this).add('component', 'fire-danger');

    const bucket = new s3.Bucket(this, 'OutputBucket', {
      bucketName: fireDangerBucketName(this.account),
      blockPublicAccess: s3.BlockPublicAccess.BLOCK_ALL,
      encryption: s3.BucketEncryption.S3_MANAGED,
      enforceSSL: true,
      objectOwnership: s3.ObjectOwnership.BUCKET_OWNER_ENFORCED,
      lifecycleRules: [{ id: 'expire-old-runs', prefix: `${cfg.keyPrefix}v1/runs/`, expiration: Duration.days(cfg.retentionDays) }],
      // Everything in it is regenerated by the next run; retained only so a
      // stack delete never fails on a non-empty bucket.
      removalPolicy: RemovalPolicy.RETAIN,
    });
    this.bucket = bucket;

    const sourceArn = `arn:${this.partition}:cloudfront::${this.account}:distribution/${distributionId || '*'}`;
    bucket.addToResourcePolicy(new iam.PolicyStatement({
      sid: 'CloudFrontReadsFireDanger',
      principals: [new iam.ServicePrincipal('cloudfront.amazonaws.com')],
      actions: ['s3:GetObject'],
      resources: [bucket.arnForObjects(`${cfg.keyPrefix}*`)],
      conditions: { StringLike: { 'AWS:SourceArn': sourceArn } },
    }));

    const logGroup = new logs.LogGroup(this, 'BuilderLogs', {
      logGroupName: '/sentinel/fire-danger-builder',
      retention: logs.RetentionDays.TWO_WEEKS,
      removalPolicy: RemovalPolicy.DESTROY,
    });
    const role = new iam.Role(this, 'BuilderRole', {
      assumedBy: new iam.ServicePrincipal('lambda.amazonaws.com'),
      description: 'Fire danger builder: own logs; read/write under fire-danger/',
    });
    role.addToPolicy(new iam.PolicyStatement({
      actions: ['logs:CreateLogStream', 'logs:PutLogEvents'],
      resources: [logGroup.logGroupArn, `${logGroup.logGroupArn}:log-stream:*`],
    }));
    role.addToPolicy(new iam.PolicyStatement({
      actions: ['s3:PutObject', 's3:GetObject'],
      resources: [bucket.arnForObjects(`${cfg.keyPrefix}*`)],
    }));
    // So a missing manifest (first run) is a 404, not a 403.
    role.addToPolicy(new iam.PolicyStatement({
      actions: ['s3:ListBucket'],
      resources: [bucket.bucketArn],
      conditions: { StringLike: { 's3:prefix': [`${cfg.keyPrefix}*`] } },
    }));

    const builder = new lambda.Function(this, 'Builder', {
      functionName: 'sentinel-fire-danger-builder',
      description: 'Publishes FEMS NFDRS station fire danger for the live map every 3 hours (cloud/fire-danger)',
      runtime: lambda.Runtime.PYTHON_3_13,
      architecture: lambda.Architecture.ARM_64,
      handler: 'lambda_handler.handler',
      // Standard library only: the source files are the whole bundle.
      code: lambda.Code.fromAsset(SERVICE_DIR, {
        exclude: ['tests', '__pycache__', '.pytest_cache', '.venv', 'README.md', 'requirements*.txt', 'pytest.ini', 'local.py'],
      }),
      memorySize: cfg.builderMemoryMb,
      timeout: Duration.seconds(cfg.builderTimeoutSeconds),
      // Runs never overlap (timeout far under the interval), so FEMS sees one
      // pull at a time without reserving account concurrency.
      role,
      logGroup,
      environment: {
        FRAMES_BUCKET: bucket.bucketName,
        PYTHONUNBUFFERED: '1',
      },
    });
    Tags.of(builder).add('service', 'fire-danger-builder');
    this.builder = builder;

    new events.Rule(this, 'BuilderSchedule', {
      description: `Publish FEMS fire danger every ${cfg.builderScheduleHours} hours`,
      schedule: events.Schedule.rate(Duration.hours(cfg.builderScheduleHours)),
      targets: [new targets.LambdaFunction(builder, { retryAttempts: 1, maxEventAge: Duration.hours(1) })],
    });

    this.#alarms(builder, alarmEmail);
    new CfnOutput(this, 'OutputBucketName', { value: bucket.bucketName });
  }

  #alarms(builder, alarmEmail) {
    const topic = new sns.Topic(this, 'AlarmTopic', { displayName: 'Sentinel fire danger alarms' });
    if (alarmEmail) topic.addSubscription(new subs.EmailSubscription(alarmEmail));
    const action = new cwActions.SnsAction(topic);
    const period = Duration.hours(3);
    const emf = (metricName, statistic) => new cloudwatch.Metric({
      namespace: FIRE_DANGER.metricsNamespace,
      metricName,
      dimensionsMap: { Service: FIRE_DANGER.dir },
      statistic,
      period,
    });
    const alarms = [
      ['BuilderErrors', 'builder failing (fire danger will go stale)', builder.metricErrors({ period, statistic: 'Sum' }), 0, 2],
      // FEMS unreachable or returning bad data, run after run.
      ['SourceErrors', 'FEMS failing for consecutive runs', emf('fire_danger_source_errors', 'Sum'), 0, 3],
      // FEMS's newest observed day is normally yesterday.
      ['DataStale', 'newest FEMS observed day more than 2 days old', emf('fire_danger_observed_age_days', 'Maximum'), 2, 2],
    ];
    for (const [name, description, metric, threshold, evaluationPeriods] of alarms) {
      new cloudwatch.Alarm(this, name, {
        alarmDescription: `fire-danger: ${description}`,
        metric,
        threshold,
        comparisonOperator: cloudwatch.ComparisonOperator.GREATER_THAN_THRESHOLD,
        evaluationPeriods,
        datapointsToAlarm: evaluationPeriods,
        treatMissingData: cloudwatch.TreatMissingData.NOT_BREACHING,
      }).addAlarmAction(action);
    }
  }
}
