/**
 * Netlify Function – global satellite fire clusters from kanari.io.
 * https://kanari.io/en/api
 *
 * Kanari clusters VIIRS, GOES and Meteosat MTG detections worldwide and
 * recomputes them every 2–5 minutes. It has no key or quota, but asks callers
 * not to poll more than once a minute and to cache. So this is the only thing
 * that calls it, and its response carries a *durable* CDN cache: every Netlify
 * edge node shares one cached copy, so Kanari sees about one request per
 * S_MAXAGE in total, however many visitors are on the map. Browsers poll this
 * route, never Kanari.
 *
 * US clusters are dropped: US fires come from NIFC/IRWIN and CAL FIRE, with
 * names, size, containment and perimeters (see usBorder.mjs).
 *
 * Clusters out over open water (more than ~5 km from any coast, lakeshore
 * or island: platforms, ships, flares at sea; see water.mjs) are dropped on
 * every refresh.
 *
 * Clusters on a known industrial heat source — gas flare, offshore platform,
 * refinery, steel mill, fuel-burning power plant — are dropped too: they burn
 * around the clock and aren't wildfires. The ~40k sites (NASA FIRMS static
 * sources, OpenStreetMap, WRI power plants) are generated by
 * scripts/build-industrial-sites.mjs into industrialSites.mjs. They're only
 * used here, so browsers never download them. Squares that have burned for
 * more than two months (see persistence.mjs, kept up by kanari-history) are
 * dropped the same way, which catches sites no list has.
 *
 * Terms: reuse must credit "Source: kanari.io" with a link (done in the UI).
 */

import { createHash } from 'node:crypto';
import { getStore } from '@netlify/blobs';
import { isInUnitedStates } from './usBorder.mjs';
import { SITES_BASE64 } from './industrialSites.mjs';
import { KANARI_EVENTS_URL, fetchKanariEvents, hasCentroid } from './kanariApi.mjs';
import { HISTORY_STORE, PERSISTENT_KEY, cellKeyOf, neighbourKeysOf } from './persistence.mjs';
import { isOverOpenWater } from './water.mjs';

export { isInUnitedStates, KANARI_EVENTS_URL };

// Kanari: "no point polling more than once a minute"; data moves every 2–5 min.
const S_MAXAGE = 120;
const SWR = 300;

// A cluster is "on" a site within these distances. VIIRS pixels are 375 m;
// a cluster seen only by geostationary satellites (GOES, MTG; 2–3 km pixels)
// can sit a few km from the true source.
const SITE_RADIUS_KM = 1;
const SITE_RADIUS_GEOSTATIONARY_KM = 3;

/** The packed site list as [lat, lon] pairs (int32 × 1e4, see the build script). */
export const INDUSTRIAL_SITES = (() => {
  const bytes = Buffer.from(SITES_BASE64, 'base64');
  // Copy into an aligned buffer: Buffer.from may hand back a pooled, unaligned slice.
  const ints = new Int32Array(new Uint8Array(bytes).buffer);
  const sites = [];
  for (let i = 0; i < ints.length; i += 2) sites.push([ints[i] / 1e4, ints[i + 1] / 1e4]);
  return sites;
})();

// Sites bucketed by 0.05° cell, built once per warm instance.
const CELL_DEG = 0.05;
const cellKey = (lat, lon) => `${Math.floor(lat / CELL_DEG)}:${Math.floor(lon / CELL_DEG)}`;
const SITE_GRID = new Map();
for (const [lat, lon] of INDUSTRIAL_SITES) {
  const key = cellKey(lat, lon);
  if (!SITE_GRID.has(key)) SITE_GRID.set(key, []);
  SITE_GRID.get(key).push([lat, lon]);
}

function distanceKm(lat1, lon1, lat2, lon2) {
  const kmPerDegLon = 111.32 * Math.cos(((lat1 + lat2) / 2) * Math.PI / 180);
  return Math.hypot((lon1 - lon2) * kmPerDegLon, (lat1 - lat2) * 111.32);
}

/** True when a cluster sits on a known industrial heat source. */
export function isOnIndustrialSite(lon, lat, { geostationaryOnly = false } = {}) {
  const radius = geostationaryOnly ? SITE_RADIUS_GEOSTATIONARY_KM : SITE_RADIUS_KM;
  // A 0.05° cell is 5.5 km tall, so one row each way covers the radius
  // north–south; cells narrow toward the poles, so the column span grows.
  const lonSpan = Math.ceil(radius / (111.32 * Math.cos(lat * Math.PI / 180) * CELL_DEG));
  const row = Math.floor(lat / CELL_DEG);
  const col = Math.floor(lon / CELL_DEG);
  for (let r = row - 1; r <= row + 1; r++) {
    for (let c = col - lonSpan; c <= col + lonSpan; c++) {
      const sites = SITE_GRID.get(`${r}:${c}`);
      if (sites?.some(([sLat, sLon]) => distanceKm(lat, lon, sLat, sLon) <= radius)) return true;
    }
  }
  return false;
}

/**
 * Each cluster is sent as a row in FIELDS order rather than an object: 20k+
 * objects repeating their keys come to ~5 MB, near the 6 MB cap on a function
 * response, and fire season only adds clusters. Rows keep it well under, and
 * times go as Unix minutes rather than ISO strings to trim it further.
 */
export const FIELDS = [
  'id', 'lon', 'lat', 'count', 'viirsCount', 'goesCount', 'mtgCount',
  'firstSeenMin', 'lastSeenMin', 'maxFrp', 'confidence',
];

const toUnixMinutes = (iso) => {
  const t = Date.parse(iso);
  return Number.isFinite(t) ? Math.round(t / 60000) : null;
};

const round4 = (n) => Math.round(n * 1e4) / 1e4;

function toRow(event) {
  const [lon, lat] = event.centroid;
  return [
    event.id, round4(lon), round4(lat), event.count ?? 0, event.viirsCount ?? 0, event.goesCount ?? 0,
    event.mtgCount ?? 0, toUnixMinutes(event.firstSeen), toUnixMinutes(event.lastSeen), event.maxFrp ?? null,
    event.confidence ?? null,
  ];
}

// The persistent squares change once a day; re-read them hourly per warm instance.
const PERSISTENT_TTL_MS = 60 * 60 * 1000;
let persistentCache = { cells: new Set(), loadedAt: 0 };

/** Squares kanari-history has found burning for 2+ months. Empty if Blobs isn't available (local dev). */
export async function loadPersistentCells() {
  if (Date.now() - persistentCache.loadedAt < PERSISTENT_TTL_MS) return persistentCache.cells;
  try {
    const keys = await getStore(HISTORY_STORE).get(PERSISTENT_KEY, { type: 'json' });
    persistentCache = { cells: new Set(Array.isArray(keys) ? keys : []), loadedAt: Date.now() };
  } catch (err) {
    console.warn('[kanari-fires] persistent squares unavailable:', err?.message || err);
    persistentCache = { cells: persistentCache.cells, loadedAt: Date.now() };
  }
  return persistentCache.cells;
}

/** True when a cluster sits in a square that has burned for 2+ months. */
export function isPersistentHeatSource(lon, lat, cells, { geostationaryOnly = false } = {}) {
  if (!cells.size) return false;
  // Geostationary-only clusters can land a square off; VIIRS ones can't.
  return geostationaryOnly
    ? neighbourKeysOf(lat, lon).some((key) => cells.has(key))
    : cells.has(cellKeyOf(lat, lon));
}

/**
 * Every cluster Kanari has for the last 24 h, outside the US, minus
 * industrial heat sources.
 * @param {object} [opts]
 * @param {Set<string>} [opts.persistentCells]  defaults to loadPersistentCells()
 * @returns {Promise<{ fields: string[], fires: Array<Array>, meta: object }>}
 */
export async function fetchGlobalFires({ fetchImpl = fetch, persistentCells } = {}) {
  const [data, persistent] = await Promise.all([
    fetchKanariEvents(fetchImpl),
    persistentCells ?? loadPersistentCells(),
  ]);

  let openWater = 0;
  let industrial = 0;
  let longBurning = 0;
  const fires = data.events
    .filter(hasCentroid)
    .filter((e) => !isInUnitedStates(e.centroid))
    .filter((e) => {
      const [lon, lat] = e.centroid;
      const geostationaryOnly = !e.viirsCount;
      if (isOverOpenWater(lon, lat)) { openWater += 1; return false; }
      if (isOnIndustrialSite(lon, lat, { geostationaryOnly })) { industrial += 1; return false; }
      if (isPersistentHeatSource(lon, lat, persistent, { geostationaryOnly })) { longBurning += 1; return false; }
      return true;
    })
    .map(toRow);
  return {
    fields: FIELDS,
    fires,
    meta: {
      fetchedAt: data.meta?.fetchedAt || new Date().toISOString(),
      // Kanari truncates without full=1; flag it if it ever does anyway.
      truncated: Boolean(data.meta?.truncated),
      openWaterDropped: openWater,
      industrialSitesDropped: industrial,
      longBurningDropped: longBurning,
      source: 'kanari.io',
    },
  };
}

export default async (request) => {
  try {
    const body = JSON.stringify(await fetchGlobalFires());
    // Lets a browser that already holds this copy get a bodiless 304 back.
    const etag = `"${createHash('sha1').update(body).digest('base64url')}"`;
    if (request?.headers?.get('If-None-Match') === etag) {
      return new Response(null, { status: 304, headers: { ETag: etag } });
    }
    return new Response(body, {
      status: 200,
      headers: {
        'Content-Type': 'application/json',
        ETag: etag,
        'Netlify-CDN-Cache-Control': `public, durable, s-maxage=${S_MAXAGE}, stale-while-revalidate=${SWR}`,
        'Cache-Control': 'public, max-age=0, must-revalidate',
      },
    });
  } catch (err) {
    console.error('[kanari-fires]', err?.message || err);
    // Never cached, so one bad upstream moment isn't served to everyone.
    return new Response(JSON.stringify({ error: 'Global fire data is temporarily unavailable.' }), {
      status: 502,
      headers: { 'Content-Type': 'application/json', 'Cache-Control': 'no-store', 'Netlify-CDN-Cache-Control': 'no-store' },
    });
  }
};

export const config = { path: '/api/kanari/fires', method: 'GET' };
